package rules

import (
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"strings"

	"spycam/backend/internal/store/gen"
)

// 生成的规则文件名固定（原子重命名目标）
const ActiveFileName = "spycam.rules"

var (
	// sid 提取用于校验；单行规则
	sidRe = regexp.MustCompile(`\bsid:\s*(\d+)\b`)
	// 允许的规则头协议/动作白名单
	headRe = regexp.MustCompile(`^(alert)\s+(tcp|udp|icmp|http|dns|tls|ssh|smb)\s+\S+\s+\S+\s*(->|<>)\s*\S+\s+\S+\s*\(`)
)

// ValidateLine 校验单条规则：单行、白名单头、sid 存在。内容安全由 suricata -T 兜底（M7）。
func ValidateLine(line string) (int64, error) {
	trimmed := strings.TrimSpace(line)
	if trimmed == "" || strings.HasPrefix(trimmed, "#") {
		return 0, fmt.Errorf("empty or comment line")
	}
	if strings.ContainsAny(trimmed, "\r\n") {
		return 0, fmt.Errorf("rule must be single line")
	}
	if !headRe.MatchString(trimmed) {
		return 0, fmt.Errorf("invalid rule head (action/protocol/direction not allowed)")
	}
	m := sidRe.FindStringSubmatch(trimmed)
	if m == nil {
		return 0, fmt.Errorf("missing sid")
	}
	var sid int64
	if _, err := fmt.Sscanf(m[1], "%d", &sid); err != nil {
		return 0, fmt.Errorf("bad sid %q", m[1])
	}
	if sid < 1000000 || sid > 99999999 {
		return 0, fmt.Errorf("sid %d out of local range", sid)
	}
	return sid, nil
}

// GenerateActiveFile 把数据库中启用的规则写成完整规则文件：
// 先写临时文件再原子重命名（避免引擎读到半截文件），目标目录即引擎只读挂载的 rules-active。
func GenerateActiveFile(dir string, enabled []gen.ListEnabledRulesRow) error {
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return fmt.Errorf("ensure rules dir: %w", err)
	}
	var b strings.Builder
	b.WriteString("# Generated by spycam api — DO NOT EDIT BY HAND\n")
	b.WriteString(fmt.Sprintf("# %d enabled rules\n\n", len(enabled)))
	for _, r := range enabled {
		line := strings.TrimSpace(r.Raw)
		if line == "" {
			continue
		}
		b.WriteString(line)
		b.WriteString("\n")
	}
	tmp := filepath.Join(dir, "."+ActiveFileName+".tmp")
	if err := os.WriteFile(tmp, []byte(b.String()), 0o644); err != nil {
		return fmt.Errorf("write tmp: %w", err)
	}
	final := filepath.Join(dir, ActiveFileName)
	if err := os.Rename(tmp, final); err != nil {
		_ = os.Remove(tmp)
		return fmt.Errorf("atomic rename: %w", err)
	}
	return nil
}
